bool LoadPetPackFromMemory(const std::uint8_t* data, std::size_t size, PetDefinition& outPet, std::string& outError) {
    ByteReader reader(data, size);

    char magic[8];
    if (!reader.ReadBytes(magic, sizeof(magic))) {
        outError = reader.Error();
        return false;
    }
    if (std::memcmp(magic, kMagic, sizeof(kMagic)) != 0) {
        outError = "not a valid pet pack (bad magic — expected NVPACK2)";
        return false;
    }

    PetDefinition pet;

    if (!reader.ReadString(pet.id) || !reader.ReadString(pet.displayName) || !reader.ReadString(pet.variantGroup)) {
        outError = reader.Error();
        return false;
    }

    std::uint32_t canvasWidth = 0;
    std::uint32_t canvasHeight = 0;
    if (!reader.ReadUint32(canvasWidth) || !reader.ReadUint32(canvasHeight)) {
        outError = reader.Error();
        return false;
    }
    pet.canvasWidth = static_cast<int>(canvasWidth);
    pet.canvasHeight = static_cast<int>(canvasHeight);

    if (!reader.ReadUint8(pet.alphaHitThreshold) || !reader.ReadFloat64(pet.visualScale) || !reader.ReadString(pet.contentVersion)) {
        outError = reader.Error();
        return false;
    }

    std::uint32_t stateCount = 0;
    if (!reader.ReadUint32(stateCount)) {
        outError = reader.Error();
        return false;
    }
    if (stateCount == 0) {
        outError = "pet has zero behavior states";
        return false;
    }
    pet.states.clear();
    pet.states.reserve(stateCount);
    for (std::uint32_t i = 0; i < stateCount; ++i) {
        BehaviorState state;
        if (!ReadState(reader, "states[" + std::to_string(i) + "]", state, outError)) {
            return false;
        }
        pet.states.push_back(std::move(state));
    }

    if (pet.canvasWidth <= 0 || pet.canvasHeight <= 0) {
        outError = "invalid canvas size";
        return false;
    }
    if (pet.visualScale <= 0.0) {
        outError = "invalid visualScale (must be > 0)";
        return false;
    }
    if (pet.id.empty()) {
        outError = "pet id must not be empty";
        return false;
    }
    if (!ValidateTargetStateIds(pet, outError)) {
        return false;
    }

    outPet = std::move(pet);
    return true;
}

bool LoadPetPackFromFile(const std::string& path, PetDefinition& outPet, std::string& outError) {
    std::ifstream file(path, std::ios::binary);
    if (!file) {
        outError = "could not open " + path;
        return false;
    }

    file.seekg(0, std::ios::end);
    const std::streamoff length = file.tellg();
    if (length < 0) {
        outError = "could not determine size of " + path;
        return false;
    }
    file.seekg(0, std::ios::beg);

    std::vector<std::uint8_t> buffer(static_cast<std::size_t>(length));
    if (!buffer.empty()) {
        file.read(reinterpret_cast<char*>(buffer.data()), length);
        if (!file) {
            outError = "failed reading " + path;
            return false;
        }
    }

    return LoadPetPackFromMemory(buffer.data(), buffer.size(), outPet, outError);
}

